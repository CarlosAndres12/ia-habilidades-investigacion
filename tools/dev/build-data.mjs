#!/usr/bin/env node
// Dev-only: the course spec -> js/data/{figures,sources,legend,badges,stamps,cast,videos,errores}.js
//   node tools/dev/build-data.mjs [path/to/especificacion-curso.md]
// Parses the same formats as revisar.py (spec §3, §4.1, §4.2, §5.1, §5.5 and §11), so the data and
// the spec never drift apart. Run tools/dev/build-content.mjs first (it writes js/data/links.js).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SPEC = path.resolve(process.argv[2] || path.join(ROOT, '..', 'especificacion-curso.md'));
const OUT = path.join(ROOT, 'js', 'data');
const spec = readFileSync(SPEC, 'utf-8');

function section(title, level) {
  const re = new RegExp('^' + '#'.repeat(level) + ' ' + title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '.*$', 'm');
  const m = re.exec(spec);
  if (!m) throw new Error('section not found: ' + title);
  const start = m.index + m[0].length;
  const rest = spec.slice(start);
  const next = new RegExp('^#{1,' + level + '} ', 'm').exec(rest);
  return rest.slice(0, next ? next.index : rest.length);
}
function tables(body) {
  const out = [];
  const lines = body.split('\n');
  for (let i = 0; i < lines.length; i++) {
    if (/^\|/.test(lines[i]) && /^\|[\s|:-]+\|$/.test(lines[i + 1] || '')) {
      const cells = (r) => r.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
      const head = cells(lines[i]);
      const rows = [];
      let j = i + 2;
      while (j < lines.length && /^\|/.test(lines[j])) { rows.push(cells(lines[j])); j++; }
      out.push({ head, rows });
      i = j;
    }
  }
  return out;
}
const strip = (s) => s.replace(/^`|`$/g, '').replace(/^«|»$/g, '');
const write = (name, file, obj, extra = '') => {
  writeFileSync(path.join(OUT, file), `/* GENERATED by tools/dev/build-data.mjs from the course spec — edit the spec and re-run. */\nwindow.IAHI.data.${name} = ${JSON.stringify(obj, null, 1)};\n${extra}`);
};

// ------------------------------------------------------------------ figures (§4.1)
const figBlock = /```js\n([\s\S]*?)```/.exec(section('4.1 Figures bank', 3))[1];
const figures = vm.runInNewContext('[' + figBlock.replace(/^\s*\/\/.*$/mg, '') + ']');
write('figures', 'figures.js', figures, 'window.IAHI.data.figuresById = {};\nwindow.IAHI.data.figures.forEach(function (f) { window.IAHI.data.figuresById[f.id] = f; });\n');

// ------------------------------------------------------------------ sources (§4.2 + links of the content)
const linksCtx = { window: { IAHI: { data: {} } } };
vm.runInNewContext(readFileSync(path.join(OUT, 'links.js'), 'utf-8'), linksCtx);
const links = linksCtx.window.IAHI.data.links;
const sources = {};
for (const [k, v] of Object.entries(links)) sources[k] = { label: v.text, url: v.url };
const srcTable = tables(section('4.2 Sources', 3))[0];
for (const r of srcTable.rows) {
  const key = strip(r[0]);
  sources[key] = Object.assign({}, sources[key] || { url: null }, { label: r[1] });
}
write('sources', 'sources.js', sources);

// ------------------------------------------------------------------ legend (§3.1)
const legTable = tables(section('3.1 Legend', 3))[0];
const legend = legTable.rows.map((r) => ({ id: strip(r[0]), label: strip(r[1]), slot: Number(r[2]), sign: r[3], question: strip(r[4]) }));
write('legend', 'legend.js', legend);

// ------------------------------------------------------------------ badges and stamps (§3.2)
const s32 = section('3.2 Marks, badges and stamps', 3);
const t32 = tables(s32);
const badges = {};
const SIGN_IDS = {
  'an open journal with a quotation mark': 'journal', 'two groups of dots split by a vertical line': 'two-groups',
  'a page with a paperclip': 'paperclip', 'a page with a folded corner': 'folded-page', 'an hourglass': 'hourglass',
  'an arrow rising toward a horizon line': 'horizon-arrow', 'a building with columns': 'columns', 'a document with a round seal': 'seal',
  'a price tag': 'price-tag', 'a podium with three steps': 'podium', 'a folder with a small warning triangle': 'warning-folder',
  'a calendar page with a check': 'calendar-check'
};
t32[0].rows.forEach((r) => { badges[strip(r[0])] = { sign: SIGN_IDS[r[1]] || 'dot', use: r[2] }; });
badges['Con matiz'] = { sign: 'caret-note' };
badges['Revisar antes de clase'] = { sign: 'calendar-cycle' };
badges['Ejemplo ilustrativo'] = { sign: 'puzzle' };
badges['Personajes inventados'] = { sign: 'two-heads' };
badges['Esquema'] = { sign: 'three-boxes' };
badges['Proyección'] = badges['Proyección'] || { sign: 'horizon-arrow' };
write('badges', 'badges.js', badges);
const stamps = t32[1].rows.map((r) => ({ id: strip(r[0]), text: strip(r[1]), sign: r[2], where: r[3] }));
write('stamps', 'stamps.js', stamps);

// ------------------------------------------------------------------ cast (§3.4, §5.1, §5.5)
const castTable = tables(section('5.1 Cast and voices', 3))[0];
const fbTable = tables(section('5.5 Browser fallback order', 3))[0];
const cfg = JSON.parse(/```json\n([\s\S]*?)```/.exec(section('5.2 voice.config.json', 3))[1]);
const LOOKS = {
  mariana: { age: 'adult', build: 'slim', skin: 'skin-3', hair: { style: 'ponytail', role: 'ink' }, glasses: 'round', clothes: [{ item: 'cardigan', role: 'accent-1' }, { item: 'bag', role: 'accent-2' }] },
  julian: { age: 'adult', build: 'stocky', skin: 'skin-5', hair: { style: 'curly-short', role: 'ink' }, beard: true, clothes: [{ item: 'shirt', role: 'accent-2' }, { item: 'vest', role: 'accent-3' }] },
  amparo: { age: 'older', build: 'medium', skin: 'skin-2', hair: { style: 'short-gray', role: 'ink-soft' }, glasses: 'reading', clothes: [{ item: 'jacket', role: 'accent-3' }, { item: 'shawl', role: 'accent-1' }] },
  rojas: { age: 'senior', build: 'tall', skin: 'skin-4', hair: { style: 'wavy-shoulder', role: 'ground' }, clothes: [{ item: 'blazer', role: 'accent-1' }, { item: 'blouse', role: 'accent-2' }] },
  tomas: { age: 'young', build: 'lanky', skin: 'skin-1', hair: { style: 'fringe', role: 'ink' }, headset: true, clothes: [{ item: 'hoodie', role: 'accent-2' }, { item: 't-shirt', role: 'accent-3' }] }
};
const NAMES = { narrador: 'Narrador', mariana: 'Mariana', julian: 'Julián', amparo: 'Amparo', rojas: 'Dra. Rojas', tomas: 'Tomás' };
const s34 = section('3.4 Cast', 3);
const descByLabel = {};
s34.split('\n').forEach((ln) => {
  const m = /^- `([^`]+)` · (.*)$/.exec(ln);
  if (m) descByLabel[m[1]] = m[2];
});
function parseFallback(cell) {
  const out = [];
  const re = /«([^»]+)»\s*(?:\+\s*|\()?(es-[A-Z]{2})?/g;
  let m;
  while ((m = re.exec(cell))) out.push({ name: m[1], lang: m[2] || null });
  return out;
}
const cast = castTable.rows.map((r) => {
  const id = strip(r[0]), label = strip(r[1]);
  const fb = fbTable.rows.find((x) => strip(x[0]) === id) || [];
  const vv = /pitch ([\d.]+), rate ([\d.]+)/.exec(fb[3] || '') || [];
  const names = parseFallback((fb[1] || '') + ' ' + (fb[2] || ''));
  return {
    id, label, name: NAMES[id] || label, voice: strip(r[3]), locale: (cfg.voices[id] || {}).locale,
    wordsPerSecond: (cfg.voices[id] || {}).wordsPerSecond || 2.4,
    description: descByLabel[label] || r[2], look: LOOKS[id] || null,
    fallback: { names, pitch: Number(vv[1] || 1), rate: Number(vv[2] || 1) }
  };
});
s34.split('\n').forEach((ln) => {
  const m = /^- `(extra-\d+)` · (.*)$/.exec(ln);
  if (m) cast.push({ id: m[1], description: m[2], poses: ['bust'] });
});
write('cast', 'cast.js', cast);

// ------------------------------------------------------------------ videos (§11)
const s11 = spec.slice(spec.indexOf('## 11. The videos'));
const LABEL2ROLE = {};
cast.forEach((c) => { if (c.label) LABEL2ROLE[c.label] = c.id; });
const VIDEO_RE = /^### V(\d+)\s*·\s*([a-z0-9-]+)\s*·\s*"(.+)"\s*$/;
const SCENE_RE = /^(\d+)\.\s+\*\*([a-z0-9][a-z0-9-]*)\*\*\s*·\s*([a-z]+)\s*·\s*min\s+(\d+(?:[.,]\d+)?)\s*$/;
const LINE_RE = /^([A-ZÁÉÍÓÚÜÑ][A-ZÁÉÍÓÚÜÑ0-9 .'-]*?):\s*"(.*)"\s*((?:\([^)]*\)\s*)*)$/;
const PAUSE_RE = /^PAUSA\s*\((\d+)\s*s\):\s*"(.+)"\s*$/;
const legendIds = legend.map((l) => l.id);

function quotes(s) {
  const out = [];
  let depth = 0, cur = '';
  for (const ch of s) {
    if (ch === '«') { if (depth > 0) cur += ch; depth++; continue; }
    if (ch === '»') { depth--; if (depth > 0) cur += ch; else { out.push(cur); cur = ''; } continue; }
    if (depth > 0) cur += ch;
  }
  return out;
}
const videos = [];
let v = null, sc = null;
for (const raw of s11.split('\n')) {
  const s = raw.trim();
  let m;
  if ((m = VIDEO_RE.exec(s))) {
    v = { id: 'v' + m[1], n: Number(m[1]), slug: m[2], title: m[3], scenes: [], pauses: [], checkpoints: [], chapters: [], legend: [] };
    videos.push(v); sc = null; continue;
  }
  if (!v) continue;
  if (/^### /.test(s)) { v = null; continue; }
  if (s.startsWith('Unit:')) {
    v.unit = (/Unit:\s*([^·]+)/.exec(s) || [])[1].trim();
    v.session = Number((/Sesión (\d+)/.exec(s) || [])[1]);
    v.slides = ((/Slides:\s*([^·]+)/.exec(s) || [])[1] || '').trim();
    const t = /Target:\s*([\d.]+)\s*[–-]\s*([\d.]+)\s*min/.exec(s);
    v.target = [Number(t[1]) * 60, Number(t[2]) * 60];
    const p = /Poster:\s*`([^`]+)`\s*@\s*([\d.]+)/.exec(s);
    v.poster = { scene: p[1], p: Number(p[2]) };
    continue;
  }
  if (s.startsWith('Chapters:')) {
    for (const c of s.matchAll(/"([^"]+)"\s*\(desde\s*`([^`]+)`\)/g)) v.chapters.push({ title: c[1], from: c[2] });
    continue;
  }
  if ((m = SCENE_RE.exec(s))) {
    sc = { id: m[2], type: m[3], min: Number(m[4].replace(',', '.')), seVe: '', figs: [], texts: {}, lines: [] };
    v.scenes.push(sc); continue;
  }
  if (!sc) continue;
  const b = /^-\s+(.*)$/.exec(s);
  if (!b) continue;
  const item = b[1];
  if (item.startsWith('Draw:')) {
    let draw = item.slice(5).trim();
    sc.draw = draw;
    const scm = /\(scale: from (-?[\d.]+) to (-?[\d.]+), step ([\d.]+), unit «([^»]*)»\)/.exec(draw);
    if (scm) { sc.scale = { from: Number(scm[1]), to: Number(scm[2]), step: Number(scm[3]), unit: scm[4] }; draw = draw.replace(scm[0], ''); }
    quotes(draw).forEach((q, i) => { sc.texts['t' + (i + 1)] = q; });
    for (const id of legendIds) if (draw.includes('`' + id + '`') && !v.legend.includes(id)) v.legend.push(id);
  } else if (item.startsWith('Se ve:')) {
    sc.seVe = (/^Se ve:\s*"(.+)"\s*$/.exec(item) || [])[1] || '';
  } else if (item.startsWith('Cifras:')) {
    sc.figs = [...item.matchAll(/`([^`]+)`/g)].map((x) => x[1]);
  } else if (item === 'Ejemplo ilustrativo') sc.ejemplo = true;
  else if (item === 'Personajes inventados') sc.ficcion = true;
  else if (item.startsWith('say:')) {
    const last = sc.lines[sc.lines.length - 1];
    if (last) last.say = (/^say:\s*"(.+)"\s*$/.exec(item) || [])[1];
  } else if ((m = PAUSE_RE.exec(item))) {
    v.pauses.push({ after: sc.id, seconds: Number(m[1]), prompt: m[2] });
  } else if ((m = LINE_RE.exec(item))) {
    const notes = m[3] || '';
    const ln = { voice: LABEL2ROLE[m[1].trim()] || m[1].trim().toLowerCase(), text: m[2] };
    const pz = /pausa\s+(\d+(?:[.,]\d+)?)\s*s/.exec(notes);
    if (pz) ln.pause = Number(pz[1].replace(',', '.'));
    if (/error de lectura/.test(notes)) ln.misreading = true;
    sc.lines.push(ln);
  }
}
write('videos', 'videos.js', videos.map((vv) => {
  const o = Object.assign({}, vv);
  o.scenes = vv.scenes.map((x) => { const y = Object.assign({}, x); delete y.draw; return y; });
  return o;
}));
// Draw briefs, for the comment at the top of each scene's draw function (not runtime data)
writeFileSync(path.join(ROOT, 'tools', 'dev', 'draw-briefs.json'), JSON.stringify(Object.fromEntries(videos.map((vv) => [vv.id, Object.fromEntries(vv.scenes.map((x) => [x.id, { draw: x.draw, texts: x.texts, scale: x.scale || null, figs: x.figs }]))])), null, 1));

// ------------------------------------------------------------------ frequent misreadings per session
const errores = {};
videos.forEach((vv) => vv.scenes.forEach((x) => x.lines.forEach((ln, i) => {
  if (!ln.misreading) return;
  const next = x.lines[i + 1];
  (errores[vv.session] = errores[vv.session] || []).push({ video: vv.id, scene: x.id, said: ln.text, correction: next ? next.text : '' });
})));
write('errores', 'errores.js', errores);

// ------------------------------------------------------------------ labels of course drawings (§3.5) and corrections (§4.8)
// rotulos.js: the final-copy labels that the course signs draw when a scene does not list them in
// its texts, in the order the §3.5 table writes them; plus the bandera-control label.
{
  const s35 = section('3.5 Course signs, places and props', 3);
  const signs = {};
  for (const line of s35.split('\n')) {
    const m = /^\|\s*`([a-z0-9-]+)`\s*\|(.*)\|([^|]*)\|\s*$/.exec(line);
    if (m) signs[m[1]] = quotes(m[2]);
  }
  const flag = (/`bandera-control`[^«]*«([^»]+)»/.exec(s35) || [])[1] || '';
  write('rotulos', 'rotulos.js', { banderaControl: flag, signs });
}
{
  const s48 = section('4.8 Corrections', 3);
  const rows = [];
  for (const line of s48.split('\n')) {
    if (!/^\|/.test(line) || /^\|\s*-/.test(line)) continue;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length < 3 || /^(Usa|Use)$/.test(cells[0])) continue;
    const unq = (c) => { const q = quotes(c); return q.length === 1 && c.trim().startsWith('«') && c.trim().endsWith('»') ? q[0] : c; };
    rows.push({ use: unq(cells[0]), noUse: cells[1], content: cells[2] });
  }
  write('correcciones', 'correcciones.js', rows);
}

console.log(`figures ${figures.length}, sources ${Object.keys(sources).length}, legend ${legend.length}, badges ${Object.keys(badges).length}, stamps ${stamps.length}, cast ${cast.length}, videos ${videos.length} (${videos.reduce((s, x) => s + x.scenes.length, 0)} scenes)`);
const noUrl = Object.entries(sources).filter(([k, s]) => !s.url).map(([k]) => k);
console.log('sources without URL:', noUrl.join(', '));
